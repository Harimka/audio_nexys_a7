// Monophonic wavetable oscillator. The 256-sample sine table and
// note-increment lookup are RTL constants (no Vivado IP blocks required).
module wavetable_oscillator (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        gate,
    input  wire [6:0]  note,
    input  wire [6:0]  velocity,
    input  wire        ready,
    output wire [15:0] sample
);
    reg [31:0] phase;
    wire [31:0] increment = note_increment(note);
    wire [15:0] wave = sine_sample(phase[31:24]);
    wire signed [16:0] centered = $signed({1'b0, wave}) - 17'sd32768;
    wire signed [23:0] scaled = (centered * $signed({1'b0, velocity})) >>> 7;

    assign sample = gate ? (16'd32768 + scaled[15:0]) : 16'd32768;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) phase <= 0;
        else if (!gate) phase <= 0;
        else if (ready) phase <= phase + increment;
    end

